type BrandSlug = keyof typeof brandIcons

// 訂閱服務名稱（含常見別名/子產品）→ 品牌 slug。用「包含比對」，
// 所以「YouTube Premium」「Netflix Standard」這種帶方案名稱的輸入也能對到。
const aliasToSlug: Record<string, BrandSlug> = {
  netflix: 'netflix',
  spotify: 'spotify',
  youtube: 'youtube',
  icloud: 'icloud',
  apple: 'apple',
  google: 'google',
  github: 'github',
  notion: 'notion',
  dropbox: 'dropbox',
  line: 'line',
  hbo: 'max',
  max: 'max',
  阿里雲: 'alibabacloud',
  alibaba: 'alibabacloud',
  cursor: 'cursor',
}

export function findBrandIcon(name: string): BrandIcon | undefined {
  const key = name.trim().toLowerCase()
  for (const [alias, slug] of Object.entries(aliasToSlug)) {
    if (key.includes(alias.toLowerCase())) return brandIcons[slug]
  }
  return undefined
}
